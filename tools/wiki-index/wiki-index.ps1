#Requires -Version 7.0
<#
.SYNOPSIS
  wiki-index - the index is generated, never maintained.
.DESCRIPTION
  Subcommands: build | lookup | diff (docs/WikiDesign.md 6).
  index.md is written from page front matter alone: topic, id, one line. Nothing here reads the old
  body - the file is rebuilt from the pages, because a hand edit is a contract violation (op 12).
  The parse and the page listing come from the shared shape
  (tools/wiki-census/wiki-shape.ps1), dot-sourced below - one shape, five instruments.
  Required args: -WikiRoot and -Report on every subcommand; -Query for lookup; -Ref for diff.
  No default encodes a task (docs/agent/TOOL-FORMAT.md). -Help prints the subcommands, no file.
#>
[CmdletBinding()]
param(
    [string]$Command,
    [string]$WikiRoot,
    [string]$Query,
    [string]$Ref,
    [string]$Report,
    [switch]$Help
)

$_shape = Join-Path (Split-Path -Path $PSScriptRoot -Parent) 'wiki-census/wiki-shape.ps1'
if (-not (Test-Path -LiteralPath $_shape -PathType Leaf)) {
    Write-Output 'USAGE wiki-index.ps1 -Command <build|lookup|diff> -WikiRoot <dir> [-Query <text>] [-Ref <git-ref>] -Report <file>   (-Help prints this)'
    Write-Output ('MISSING args=shared-shape (no wiki-shape.ps1 at ' + ($_shape -replace '\\', '/') + ')')
    Write-Output 'VERDICT fail=1'
    exit 1
}
. $_shape

# ---------------------------------------------------------------- index rows
function Get-WikiIndexRow {
    # One row per page from front matter alone: topic, id, one line. The body is never opened, which
    # is what keeps a 200-page index a free op (docs/WikiDesign.md 6).
    param($Page)
    $pageType = ''
    if ($null -ne $Page.Fields -and $Page.Fields.Contains('PageType')) { $pageType = [string]$Page.Fields['PageType'] }
    if ($pageType -eq '') { $pageType = '(no PageType)' }
    $summary = ''
    if ($null -ne $Page.Fields -and $Page.Fields.Contains('Summary')) { $summary = [string]$Page.Fields['Summary'] }
    $title = ''
    if ($null -ne $Page.Fields -and $Page.Fields.Contains('Title')) { $title = [string]$Page.Fields['Title'] }
    if ($title -eq '') { $title = $Page.Stem }
    $id = ''
    if ($null -ne $Page.Fields -and $Page.Fields.Contains('Target')) { $id = [string]$Page.Fields['Target'] }
    if ($id -eq '') { $id = $Page.Stem }
    $text = '- [[' + $Page.Stem + ']] - ' + $title + ' | id: ' + $id
    if ($summary -ne '') { $text += ' - ' + $summary }
    return [pscustomobject]@{ PageType = $pageType; Rel = $Page.Rel; Text = $text; HasSummary = ($summary -ne '') }
}

# ---------------------------------------------------------------- build
function Invoke-IndexBuild {
    param($WikiFull)
    $lines = @()
    $set = Get-WikiPageSet -WikiRoot $WikiFull
    $pages = @($set.Pages)
    $rows = @()
    foreach ($page in $pages) { $rows += @(Get-WikiIndexRow -Page $page) }
    $header = @(
        '# Index',
        '',
        '<!-- GENERATED by tools/wiki-index/wiki-index.ps1 -Command build. Do not edit: the rows come',
        '<!-- from each page''s front matter (PageType, Title, Target, Summary) and a hand edit is lost',
        '<!-- on the next build (docs/WikiDesign.md 6, op 12 "regenerable in one pass"). -->',
        '')
    $body = @()
    foreach ($pageType in @($rows | ForEach-Object { $_.PageType } | Sort-Object -Unique)) {
        $group = @($rows | Where-Object { $_.PageType -eq $pageType })
        $body += ('## ' + $pageType + ' (' + $group.Count + ')')
        $body += ''
        $body += @($group | ForEach-Object { $_.Text } | Sort-Object)
        $body += '' }
    $indexPath = Join-Path $WikiFull 'index.md'
    ($header + $body) | Out-File -LiteralPath $indexPath -Encoding utf8
    $written = @(Read-WikiLines -Path $indexPath)
    $bodyRows = @($written | Where-Object { $_ -cmatch '^- \[\[' }).Count
    $noSummary = @($rows | Where-Object { -not $_.HasSummary })
    $lines += ('index = ' + (Get-WikiRelPath -Path $indexPath) + '  (' + $written.Count + ' lines written and re-read)')
    $lines += ('files = ' + $set.All.Count + '  (of which ' + $set.Strays.Count + ' stray .md are not indexed: a stray is wiki-lint to judge, not a row)')
    $lines += ('pages = ' + $pages.Count)
    $lines += ('index_rows = ' + $bodyRows + ' of ' + $pages.Count +
               '  (row lines counted in the file that was just written, against the pages on disk)')
    $lines += ('indexed = ' + $bodyRows + ' unindexed = ' + ($pages.Count - $bodyRows))
    $lines += ('groups = ' + (@($rows | ForEach-Object { $_.PageType } | Sort-Object -Unique).Count) +
               '  (one per PageType; a page with no PageType lands in (no PageType))')
    foreach ($row in $noSummary) {
        $lines += ('  NO_SUMMARY ' + $row.Rel + ' : the row is id-only, so the index says nothing about it') }
    if ($pages.Count -eq 0) {
        $lines += 'vacuity: pages=0 - index_rows = 0 of 0 is an empty index, not a working one (9)' }
    # Abs so a too-large index cannot print a negative fail, which 'exit 1 if fail -gt 0' would swallow.
    return @{ Lines = $lines; Fail = [Math]::Abs($pages.Count - $bodyRows) }
}

# ---------------------------------------------------------------- lookup
function Invoke-IndexLookup {
    param($WikiFull, [string]$Text)
    $lines = @()
    $set = Get-WikiPageSet -WikiRoot $WikiFull
    $pages = @($set.Pages)
    $hits = @()
    foreach ($page in $pages) {
        $target = ''
        if ($null -ne $page.Fields -and $page.Fields.Contains('Target')) { $target = [string]$page.Fields['Target'] }
        $title = ''
        if ($null -ne $page.Fields -and $page.Fields.Contains('Title')) { $title = [string]$page.Fields['Title'] }
        $summary = ''
        if ($null -ne $page.Fields -and $page.Fields.Contains('Summary')) { $summary = [string]$page.Fields['Summary'] }
        # A target id and a topic phrase are the two questions the index answers (docs/WikiDesign.md 6).
        $fields = [ordered]@{ target = $target; stem = $page.Stem; title = $title; summary = $summary }
        $where = ''
        foreach ($field in $fields.Keys) {
            $value = [string]$fields[$field]
            if ($value -eq '') { continue }
            if ($value -like ('*' + $Text + '*')) {
                if ($where -eq '') { $where = $field }
                break } }
        if ($where -eq '') { continue }
        $hits += ('  HIT ' + $page.Rel + '  (matched ' + $where + ')') }
    $lines += ('query = ' + $Text)
    $lines += ('hits = ' + $hits.Count + ' of ' + $pages.Count +
               '  (pages whose target, stem, title or summary contains the query)')
    $lines += ('misses = ' + ($pages.Count - $hits.Count))
    $lines += $hits
    if ($pages.Count -eq 0) {
        $lines += 'vacuity: pages=0 - hits = 0 of 0 is no page matching, not a working lookup (9)' }
    # lookup reports: a query with no page is a question the wiki has not answered yet, not a fault.
    return @{ Lines = $lines; Fail = 0 }
}

# ---------------------------------------------------------------- diff
function Invoke-IndexDiff {
    param($WikiFull, [string]$Ref)
    $lines = @()
    $fail = 0
    $set = Get-WikiPageSet -WikiRoot $WikiFull
    $pages = @($set.Pages)
    $repoFull = ''
    $repoOut = @(git -C $WikiFull rev-parse --show-toplevel 2>$null)
    if ($LASTEXITCODE -eq 0 -and $repoOut.Count -ge 1) { $repoFull = (([string]$repoOut[0]).Trim() -replace '\\', '/') }
    $lines += ('ref = ' + $Ref)
    $lines += ('repo_root = ' + $repoFull)
    if ($repoFull -eq '') {
        $lines += '  FAIL: the wiki root is not inside a git repository, so nothing can be diffed against a ref'
        return @{ Lines = $lines; Fail = 1 } }
    # The wiki root as the repo sees it: git pathspecs are repo-relative with forward slashes.
    $wikiRel = ''
    if ($WikiFull -replace '\\', '/' -like ($repoFull + '/*')) {
        $wikiRel = (($WikiFull -replace '\\', '/') -replace ('^' + [regex]::Escape($repoFull) + '/'), '') }
    $changed = @()
    $diffOut = @(git -C $repoFull diff --name-only $Ref -- $wikiRel 2>$null)
    if ($LASTEXITCODE -ne 0) {
        $lines += ('  FAIL: git diff --name-only ' + $Ref + ' did not run, so moved = 0 would be a lie')
        return @{ Lines = $lines; Fail = 1 } }
    foreach ($name in $diffOut) { if (([string]$name).Trim() -ne '') { $changed += (([string]$name).Trim() -replace '\\', '/') } }
    # A page that has never been committed is new content: git diff cannot see it, ls-files can.
    $untracked = @()
    $others = @(git -C $repoFull ls-files --others --exclude-standard -- $wikiRel 2>$null)
    foreach ($name in $others) { if (([string]$name).Trim() -ne '') { $untracked += (([string]$name).Trim() -replace '\\', '/') } }
    $all = @(@($changed) + @($untracked)) | Sort-Object -Unique
    $movedItems = @()
    foreach ($page in $pages) {
        # git answers in repo-relative paths, the page list in wiki-relative ones: one word, joined.
        $rel = $wikiRel + '/' + $page.Rel
        $kind = ''
        if ($changed -contains $rel) { $kind = 'modified since ' + $Ref }
        elseif ($untracked -contains $rel) { $kind = 'untracked (never committed)' }
        if ($kind -ne '') { $movedItems += ('  MOVED ' + $page.Rel + ' : ' + $kind) } }
    $lines += ('diff_paths = ' + $changed.Count + '  (repo paths git diff names under ' + $wikiRel + ')')
    $lines += ('untracked_paths = ' + $untracked.Count)
    $lines += ('all_changed_paths = ' + $all.Count + '  (informational: repo paths, not page paths)')
    $lines += ('moved = ' + $movedItems.Count + ' of ' + $pages.Count +
               '  (pages whose file changed since the ref or was never committed)')
    $lines += ('unchanged = ' + ($pages.Count - $movedItems.Count))
    $lines += $movedItems
    if ($pages.Count -eq 0) {
        $lines += 'vacuity: pages=0 - moved = 0 of 0 is an empty wiki, not a wiki that has not moved (9)' }
    # diff reports what moved; it does not judge it. Deciding that a moved page needs a re-read is
    # wiki-reconcile's job (docs/WikiDesign.md 5: two questions, two instruments).
    return @{ Lines = $lines; Fail = $fail }
}




# ---------------------------------------------------------------- dispatcher
# The dispatcher. Requiredness lives here, not in a Mandatory attribute, so a bare run
# prints the contract instead of prompting (docs/agent/TOOL-FORMAT.md).
$subcommands = @('build', 'lookup', 'diff')
$usage = 'wiki-index.ps1 -Command <build|lookup|diff> -WikiRoot <dir> [-Query <text>] [-Ref <git-ref>] -Report <file>   (-Help prints this)'
$argLines = @('  required: -WikiRoot and -Report on every subcommand; -Query for lookup; -Ref for diff.',
              '  build writes <WikiRoot>/index.md - the index is generated, never edited (docs/WikiDesign.md 6) -',
              '  and prints the path it resolved; a hand edit is lost on the next build on purpose.',
              '  fail=1 means the index does not match the pages. lookup and diff report, they do not judge:',
              '  deciding that a moved page must be re-read is wiki-reconcile (docs/WikiDesign.md 5).')
if ($Help) {
    Exit-WikiHelp -ToolName 'wiki-index' -Subcommands $subcommands -Usage $usage -ArgLines $argLines }
if ([string]::IsNullOrWhiteSpace($Command)) {
    Exit-WikiUsage -Usage $usage -Missing 'Command' -ExtraLines @('  subcommand: ' + ($subcommands -join ' | ')) }
if ([string]::IsNullOrWhiteSpace($Report)) { Exit-WikiUsage -Usage $usage -Missing 'Report' }
# Every root is tested before it is resolved: passing '' to a Mandatory [string] parameter throws
# and lets the script run on with a $null root, which is how a contract bug prints a false green.
if ([string]::IsNullOrWhiteSpace($WikiRoot)) { Exit-WikiUsage -Usage $usage -Missing 'WikiRoot' }
$wikiFull = Resolve-WikiRequiredRoot -Name 'WikiRoot' -Value $WikiRoot -Usage $usage
switch -CaseSensitive ($Command) {
    'build' { $run = Invoke-IndexBuild -WikiFull $wikiFull }
    'lookup' {
        if ([string]::IsNullOrWhiteSpace($Query)) { Exit-WikiUsage -Usage $usage -Missing 'Query' }
        $run = Invoke-IndexLookup -WikiFull $wikiFull -Text $Query }
    'diff' {
        if ([string]::IsNullOrWhiteSpace($Ref)) { Exit-WikiUsage -Usage $usage -Missing 'Ref' }
        # A ref that does not resolve is a usage failure, never a run that prints moved = 0: an empty
        # diff and a nonsense ref must not share a print (docs/agent/TOOL-FORMAT.md, Stop condition).
        $repoOut = @(git -C $wikiFull rev-parse --verify --quiet ($Ref + '^{commit}') 2>$null)
        if ($LASTEXITCODE -ne 0 -or $repoOut.Count -lt 1) {
            Exit-WikiUsage -Usage $usage -Missing ('Ref (does not resolve to a commit: ' + $Ref + ')') }
        $run = Invoke-IndexDiff -WikiFull $wikiFull -Ref $Ref }
    default { Exit-WikiUsage -Usage $usage -Missing ('Command (unknown: ' + $Command + ')') }
}
if ($null -eq $run) {
    Exit-WikiUsage -Usage $usage -Missing ('internal (subcommand ' + $Command + ' returned no result)') }
$out = @()
$out += ('wiki-index command=' + $Command + '  shape=' + $script:WikiShapeVersion)
$out += ('wiki_root = ' + (Get-WikiRelPath -Path $wikiFull) + '  cwd = ' + ((Get-Location).Path -replace '\\', '/'))
$out += $run.Lines
$out += ('VERDICT fail=' + $run.Fail)
Write-WikiRun -ReportPath $Report -Lines $out
if ($run.Fail -gt 0) { exit 1 }
exit 0
